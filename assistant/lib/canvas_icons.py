_ALIASES = {"trophy": "cup"}
_ICON_NAME_RE = re.compile(r"^[a-z0-9_]{1,60}$")
_RAW: Optional[dict[str, str]] = None


def _raw() -> dict[str, str]:
    global _RAW
    if _RAW is None:
        try:
            _RAW = json.loads(ICONS_FILE.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            _RAW = {}
    return _RAW


def _full_key(name: str) -> str:
    raw = _raw()
    short = _ALIASES.get(name, name)
    for k in (short, f"{short}_outline_24", f"{short}_24"):
        if k in raw:
            return k
    return ""


def norm(name: object) -> str:
    """Короткое имя иконки или "" — для значений от модели и из редактора."""
    s = str(name or "").strip().lower().removesuffix("_outline_24").removesuffix("_24")
    if not _ICON_NAME_RE.match(s) or not _full_key(s):
        return ""
    return s


def inner(name: str) -> str:
    """SVG-содержимое иконки (пути без <svg>) по короткому имени."""
    k = _full_key(name)
    return _raw().get(k, "") if k else ""


def svg(name: object, cls: str = "ico") -> str:
    """<svg> иконки (currentColor) или "" — неизвестные имена молча пропускаем."""
    n = norm(name)
    body = inner(n) if n else ""
    if not body:
        return ""
    return (f'<svg class="{cls}" data-icon="{n}" viewBox="0 0 24 24" width="24" height="24" fill="currentColor" '
            f'aria-hidden="true">{body}</svg>')


def catalog() -> dict[str, str]:
    """Иконки для модели и меню редактора: только те, что есть в наборе."""
    return {k: v for k, v in CATALOG.items() if _full_key(k)}


def prompt_list() -> str:
    return "; ".join(f"{k} — {v}" for k, v in catalog().items())
